export const GLYPH_W = 3;
export const GLYPH_H = 5;

export type Glyph = readonly (readonly boolean[])[];

export const GLYPHS: Record<string, Glyph> = Object.fromEntries(
  Object.entries(ART).map(([char, rows]) => {
    if (rows.length !== GLYPH_H || rows.some((r) => r.length !== GLYPH_W)) {
      throw new Error(`Glyph "${char}" is not ${GLYPH_W}x${GLYPH_H}`);
    }
    return [char, rows.map((row) => [...row].map((cell) => cell === '#'))];
  }),
);
